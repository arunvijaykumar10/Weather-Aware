def is_graphhopper_key(key: Optional[str]) -> bool:
    """Return True if the key matches the GraphHopper 36-character UUID format."""
    if not key or not isinstance(key, str):
        return False
    stripped = key.strip()
    return len(stripped) == 36 and stripped.count("-") == 4


